// واجهة أساسية (Base Interface) تحتوي على الحقول المشتركة لكل كيانات النظام
export interface BaseEntity {
  id: string;
  createdAt: Date;
  updatedAt: Date;
}

// ----------------------------------------------------------------------
// 1. إدارة المخازن (Warehouses)
// ----------------------------------------------------------------------
export interface Warehouse extends BaseEntity {
  name: string;          // اسم المخزن (مثل: المخزن الرئيسي، فرع أبو المطامير)
  location?: string;     // عنوان أو تفاصيل موقع المخزن (اختياري)
  isMain: boolean;       // يحدد ما إذا كان هذا هو المخزن الأساسي (يجب أن يكون هناك مخزن واحد فقط يحمل true)
  isActive: boolean;     // للتعطيل المؤقت (Soft Delete) للمخازن الفرعية
}


// ----------------------------------------------------------------------
// 2. إدارة الخزائن (Cashboxes / Treasuries)
// ----------------------------------------------------------------------

// أنواع الخزائن المتاحة في النظام
export type CashboxType = 'cash' | 'bank' | 'wallet' | 'digital';

export interface Cashbox extends BaseEntity {
  name: string;          // اسم الخزينة (مثل: الخزنة الرئيسية، خزنة الكاشير، فودافون كاش)
  type: CashboxType;     // نوع الخزينة (نقدية، بنك، محفظة إلكترونية، دفع رقمي)
  isMain: boolean;       // يحدد ما إذا كانت هذه هي الخزنة الرئيسية للنظام (يُسمح بواحدة فقط)
  isDaily: boolean;      // يحدد ما إذا كانت هذه هي خزنة رصيد اليوم (يُسمح بواحدة فقط)
  isActive: boolean;     // للتعطيل المؤقت للحسابات والخزائن الإضافية
  balance: number;       // الرصيد الحالي (تنبيه: هذا الحقل للعرض فقط ولتحسين الأداء - Caching، لا يُعدل يدوياً بل عبر الحركات المالية)
  description?: string;  // وصف إضافي أو رقم حساب (اختياري)
}

// ----------------------------------------------------------------------
// ملاحظة معمارية للمستقبل (Architecture Note):
// أي تغيير في حقل `balance` داخل Cashbox يجب أن يتم عبر Transaction 
// تسجل حركة (Transaction/Ledger) أولاً، ثم تُحدث هذا الحقل كـ (Cached Value).
// ----------------------------------------------------------------------
