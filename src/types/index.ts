// عند بناء الأصناف، لن نضع الرصيد والتكلفة في جدول الصنف الرئيسي.
// بل سننشئ جدول وسيط (مثلاً ItemWarehouseStock) يحتوي على:
// itemId, warehouseId, quantity, weightedAverageCost
// هذا يضمن أن كل مخزن يحتفظ برصيده وتكلفته المستقلة تماماً كما طلبت.
